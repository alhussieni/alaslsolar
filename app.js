const LANG_NAMES = { en: "English", ar: "العربية", es: "Español", zh: "中文" };

function applyLanguage(lang) {
  const fallback = translations.en;
  const selected = { ...fallback, ...(translations[lang] || {}) };
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (selected[key]) {
      element.textContent = selected[key];
    }
  });

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.classList.toggle("active", button.dataset.lang === lang);
  });

  // Update globe button label
  const labelEl = document.getElementById("langLabel");
  if (labelEl) labelEl.textContent = LANG_NAMES[lang] || lang.toUpperCase();

  // Close dropdown after selection
  const dropdown = document.getElementById("langDropdown");
  const toggle = document.getElementById("langToggle");
  if (dropdown) dropdown.classList.remove("open");
  if (toggle) toggle.setAttribute("aria-expanded", "false");

  localStorage.setItem("alasl-lang", lang);
}

function initMenu() {
  const toggle = document.querySelector("[data-menu-toggle]");
  const menu = document.getElementById("siteMenu");
  if (!toggle || !menu) return;

  toggle.addEventListener("click", () => {
    const isOpen = menu.classList.toggle("open");
    toggle.setAttribute("aria-expanded", String(isOpen));
  });

  document.addEventListener("click", (event) => {
    if (!menu.classList.contains("open")) return;
    if (menu.contains(event.target) || toggle.contains(event.target)) return;
    menu.classList.remove("open");
    toggle.setAttribute("aria-expanded", "false");
  });
}

