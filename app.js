let currentArticleData = null;

function renderArticleNotFound() {
  const loading = document.querySelector("[data-article-loading]");
  const notFound = document.querySelector("[data-article-not-found]");
  const content = document.querySelector("[data-article-content]");
  if (loading) loading.hidden = true;
  if (content) content.hidden = true;
  if (notFound) notFound.hidden = false;
}

function renderArticleDetail(article, lang) {
  if (!article) return;
  currentArticleData = article;
  const activeLang = lang || localStorage.getItem("alasl-lang") || "en";

  const loading = document.querySelector("[data-article-loading]");
  const notFound = document.querySelector("[data-article-not-found]");
  const content = document.querySelector("[data-article-content]");
  if (loading) loading.hidden = true;
  if (notFound) notFound.hidden = true;
  if (!content) return;
  content.hidden = false;

  const title = getLocalizedField(article, "title", activeLang) || article.title || "";
  const body =
    getLocalizedField(article, "content", activeLang) ||
    getLocalizedField(article, "body", activeLang) ||
    getLocalizedField(article, "summary", activeLang) ||
    article.summary ||
    "";
  const image = normalizeAssetPath(article.image_url || "solar.jpg");
  const date = article.created_at ? new Date(article.created_at).toLocaleDateString() : "";

  document.title = `${title} | Al Asl Solar`;

  const titleEl = document.getElementById("articleTitle");
  if (titleEl) titleEl.textContent = title;

  const imageEl = content.querySelector("[data-article-image]");
  if (imageEl) {
    if (image) {
      imageEl.src = image;
      imageEl.alt = title;
      imageEl.hidden = false;
    } else {
      imageEl.hidden = true;
    }
  }

  const dateEl = content.querySelector("[data-article-date]");
  if (dateEl) dateEl.textContent = date;

  const bodyEl = content.querySelector("[data-article-body]");
  if (bodyEl) {
    const trimmed = (body || "").trim();
    // New articles are written with the rich text editor and stored as
    // ready-to-render HTML (start with a tag). Older articles were written
    // as plain Markdown text and need conversion before rendering.
    const isHtml = trimmed.startsWith("<");
    bodyEl.innerHTML = isHtml
      ? trimmed
      : (typeof marked !== "undefined" ? marked.parse(trimmed) : trimmed);
  }
}

async function initArticleDetail() {
  const root = document.querySelector("[data-article-detail]");
  if (!root) return;

  const params = new URLSearchParams(window.location.search);
  const slug = params.get("slug");
  const lang = localStorage.getItem("alasl-lang") || "en";

  if (!slug) {
    renderArticleNotFound();
    return;
  }

  const client = typeof getAlaslSupabase === "function" ? getAlaslSupabase() : null;
  if (!client) {
    renderArticleNotFound();
    return;
  }

  try {
    const { data, error } = await client
      .from("articles")
      .select("*")
      .eq("slug", slug)
      .eq("published", true)
      .maybeSingle();

    if (error || !data) {
      renderArticleNotFound();
      return;
    }

    renderArticleDetail(data, lang);
  } catch (error) {
    renderArticleNotFound();
  }
}

function initLangDropdown() {
  const toggle = document.getElementById("langToggle");
  const dropdown = document.getElementById("langDropdown");
  if (!toggle || !dropdown) return;

  toggle.addEventListener("click", (e) => {
    e.stopPropagation();
    const isOpen = dropdown.classList.toggle("open");
    toggle.setAttribute("aria-expanded", String(isOpen));
  });

  document.addEventListener("click", (e) => {
    if (!dropdown.classList.contains("open")) return;
    if (dropdown.contains(e.target) || toggle.contains(e.target)) return;
    dropdown.classList.remove("open");
    toggle.setAttribute("aria-expanded", "false");
  });

  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape" && dropdown.classList.contains("open")) {
      dropdown.classList.remove("open");
      toggle.setAttribute("aria-expanded", "false");
      toggle.focus();
    }
  });
}

function detectVisitorLanguage() {
  const supported = ["ar", "en", "es", "zh"];
  const browserLangs = navigator.languages && navigator.languages.length
    ? navigator.languages
    : [navigator.language || "en"];

  for (const raw of browserLangs) {
    const code = raw.toLowerCase().split("-")[0];
    if (supported.includes(code)) return code;
  }
  return "en";
}

// ── Admin link visibility ────────────────────────────────────────────────────
// Show the "Admin" nav link ONLY when a Supabase session is active.
// The link is hidden via CSS (.admin-link { display: none !important }) by default.
async function initAdminLink() {
  try {
    // Supabase SDK and config may not be loaded on every page — guard carefully
    if (typeof getAlaslSupabase !== "function") return;
    const client = getAlaslSupabase();
    if (!client) return;

    const showIfLoggedIn = (session) => {
      const links = document.querySelectorAll(".admin-link");
      links.forEach((el) => {
        if (session) {
          el.classList.add("admin-visible");
        } else {
          el.classList.remove("admin-visible");
        }
      });
    };

    // Check current session on page load
    const { data } = await client.auth.getSession();
    showIfLoggedIn(data?.session ?? null);

    // Keep in sync with auth state changes (login / logout)
    client.auth.onAuthStateChange((_event, session) => {
      showIfLoggedIn(session);
    });
  } catch (e) {
    // If anything fails, admin link stays hidden — safe by default
  }
}

// ── Project gallery lightbox (slider with thumbnail strip) ─────────────────
function initProjectGallery() {
  const items = Array.from(document.querySelectorAll(".project-gallery-item"));
  if (!items.length) return;

  const photos = items.map((el) => ({
    full: el.dataset.full,
    caption: el.dataset.caption || "",
  }));

  const box = document.createElement("div");
  box.className = "project-lightbox";
  box.innerHTML = `
    <button type="button" class="project-lightbox-close" aria-label="إغلاق">×</button>
    <div class="project-lightbox-main">
      <button type="button" class="project-lightbox-prev" aria-label="السابق">‹</button>
      <img src="" alt="">
      <button type="button" class="project-lightbox-next" aria-label="التالي">›</button>
    </div>
    <p class="project-lightbox-caption"></p>
    <div class="project-lightbox-thumbs"></div>
  `;
  document.body.appendChild(box);

  const mainImg = box.querySelector(".project-lightbox-main img");
  const caption = box.querySelector(".project-lightbox-caption");
  const thumbsWrap = box.querySelector(".project-lightbox-thumbs");

  photos.forEach((photo, idx) => {
    const thumb = document.createElement("button");
    thumb.type = "button";
    thumb.className = "project-lightbox-thumb";
    thumb.innerHTML = `<img src="${photo.full}" alt="">`;
    thumb.addEventListener("click", () => show(idx));
    thumbsWrap.appendChild(thumb);
  });

  const thumbEls = Array.from(thumbsWrap.children);
  let current = 0;

  function show(idx) {
    current = (idx + photos.length) % photos.length;
    const photo = photos[current];
    mainImg.src = photo.full;
    mainImg.alt = photo.caption || "";
    caption.textContent = photo.caption;
    thumbEls.forEach((el, i) => el.classList.toggle("active", i === current));
    thumbEls[current]?.scrollIntoView({ block: "nearest", inline: "center" });
  }

  function open(idx) {
    show(idx);
    box.classList.add("open");
    document.body.style.overflow = "hidden";
  }

  function close() {
    box.classList.remove("open");
    document.body.style.overflow = "";
  }

  items.forEach((el, idx) => el.addEventListener("click", () => open(idx)));
  box.querySelector(".project-lightbox-close").addEventListener("click", close);
  box.querySelector(".project-lightbox-prev").addEventListener("click", () => show(current - 1));
  box.querySelector(".project-lightbox-next").addEventListener("click", () => show(current + 1));
  box.addEventListener("click", (e) => {
    if (e.target === box) close();
  });
  document.addEventListener("keydown", (e) => {
    if (!box.classList.contains("open")) return;
    if (e.key === "Escape") close();
    if (e.key === "ArrowLeft") show(current - 1);
    if (e.key === "ArrowRight") show(current + 1);
  });
}

document.addEventListener("DOMContentLoaded", () => {
  // Static per-language article pages (loaded via article-lang-switcher.js) declare
  // their own language in the HTML source (<html lang="ar|en|es|zh">) — that
  // declaration IS the language of the page's actual content, since each language
  // lives in its own physical file. On these pages we must NOT let a stale
  // localStorage value or the visitor's browser language override it, or the
  // page ends up with a nav/footer in one language and an article body in another.
  const isStaticArticlePage = !!document.querySelector('script[src*="article-lang-switcher"]');
  const supportedLangs = ["en", "ar", "es", "zh"];
  const pageDeclaredLang = document.documentElement.getAttribute("lang");

  let savedLang;
  if (isStaticArticlePage && supportedLangs.includes(pageDeclaredLang)) {
    savedLang = pageDeclaredLang;
    // Keep the site-wide preference in sync so navigating back to app pages
    // (index, about, products…) continues in the same language.
    localStorage.setItem("alasl-lang", savedLang);
  } else {
    const storedLang = localStorage.getItem("alasl-lang");
    savedLang = storedLang || detectVisitorLanguage();
    localStorage.setItem("alasl-lang", savedLang);
  }
  document.documentElement.lang = savedLang;
  document.documentElement.dir = savedLang === "ar" ? "rtl" : "ltr";

  initMenu();
  initNavigationState();
  // initAdminLink needs Supabase SDK which loads at end of body — run after all scripts are ready
  if (typeof getAlaslSupabase === "function") {
    initAdminLink();
  } else {
    window.addEventListener("load", initAdminLink);
  }
  initContactForm();
  initProjectFilters();
  initProjects();
  initArticles();
  initArticleDetail();
  initLangDropdown();
  initProjectGallery();

  applyLanguage(savedLang);

  document.querySelectorAll("[data-lang]").forEach((button) => {
    button.addEventListener("click", () => {
      applyLanguage(button.dataset.lang);
      if (currentArticlesData) {
        renderArticles(currentArticlesData, button.dataset.lang);
      }
      if (currentArticleData) {
        renderArticleDetail(currentArticleData, button.dataset.lang);
      }
    });
  });

  // Scroll reveal
  const revealObserver = new IntersectionObserver(
    (entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("visible");
          revealObserver.unobserve(entry.target);
        }
      });
    },
    { threshold: 0.08, rootMargin: "0px 0px -40px 0px" }
  );
  document.querySelectorAll(".reveal").forEach((el) => revealObserver.observe(el));
});
