function escapeHtml(value) {
  return String(value || "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#039;");
}

function normalizeAssetPath(path) {
  if (!path) return "solar.jpg";
  if (/^https?:\/\//i.test(path)) return path;
  return path.replace(/^\//, "");
}

function projectMeta(project) {
  return [project.location, project.capacity, project.year].filter(Boolean).join(" | ");
}

function renderProjects(projects) {
  const grid = document.querySelector("[data-projects-grid]");
  if (!grid || !Array.isArray(projects) || projects.length === 0) return;

  grid.innerHTML = projects.map((project) => {
    const image = normalizeAssetPath(project.image_url || project.image);
    const meta = projectMeta(project);
    const tag = project.slug ? "a" : "article";
    const href = project.slug ? ` href="projects/${escapeHtml(project.slug)}.html"` : "";

    return `
      <${tag} class="project-card" data-category="${escapeHtml(project.category || "Project")}" style="--project-image:url('${escapeHtml(image)}')"${href}>
        <span>${escapeHtml(project.category || "Project")}</span>
        <h2>${escapeHtml(project.title)}</h2>
        ${meta ? `<p class="project-meta">${escapeHtml(meta)}</p>` : ""}
      </${tag}>
    `;
  }).join("");
  applyProjectFilter(document.querySelector("[data-project-filters] .active")?.dataset.filter || "all");
}

function applyProjectFilter(filter) {
  const cards = document.querySelectorAll("[data-projects-grid] .project-card");
  cards.forEach((card) => {
    const category = card.dataset.category || "";
    card.hidden = filter !== "all" && category !== filter;
  });
}

function initProjectFilters() {
  const filters = document.querySelector("[data-project-filters]");
  if (!filters) return;

  filters.addEventListener("click", (event) => {
    const button = event.target.closest("button[data-filter]");
    if (!button) return;
    filters.querySelectorAll("button").forEach((item) => item.classList.remove("active"));
    button.classList.add("active");
    applyProjectFilter(button.dataset.filter);
  });
}

async function initProjects() {
  const grid = document.querySelector("[data-projects-grid]");
  if (!grid) return;

  const client = typeof getAlaslSupabase === "function" ? getAlaslSupabase() : null;
  if (client) {
    try {
      const { data, error } = await client
        .from("projects")
        .select("title,category,location,capacity,year,summary,image_url,slug,published,sort_order,created_at")
        .eq("published", true)
        .order("sort_order", { ascending: true })
        .order("created_at", { ascending: false });

      if (!error && data && data.length) {
        renderProjects(data);
        return;
      }
    } catch (error) {
      // Fall back to local JSON.
    }
  }

  try {
    const response = await fetch("data/projects.json", { cache: "no-store" });
    if (!response.ok) return;
    const data = await response.json();
    renderProjects(data.projects);
  } catch (error) {
    // Keep the static fallback cards when running from file:// or if JSON is unavailable.
  }
}

// Tries "<base>_<lang>" first, falls back to "<base>_en", then plain "<base>".
// Lets articles display correctly even if only some language columns are filled in.
function getLocalizedField(record, baseName, lang) {
  if (!record) return "";
  const candidates = [`${baseName}_${lang}`, `${baseName}_ar`, `${baseName}_en`, baseName];
  for (const key of candidates) {
    if (record[key]) return record[key];
  }
  return "";
}

